// Compile the already-owned SVG paths, not a newly approximated logo or raster texture.
// Uses the existing Playwright dev dependency only to provide DOMParser for SVGLoader.
import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import { startServer } from '../server.mjs';

const sourceURL=new URL('../../LoomOS-panda-ink-clean.svg',import.meta.url);
const source=await readFile(sourceURL,'utf8');
const sourceSha256=createHash('sha256').update(source).digest('hex');
const crop=[385,565,645,820];
const server=startServer(0);await once(server,'listening');
const origin=`http://127.0.0.1:${server.address().port}`;
const launch=process.env.PLAYWRIGHT_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH}:existsSync('/Applications/Google Chrome.app')?{channel:'chrome'}:{};
let browser;
try{
  browser=await chromium.launch({...launch,headless:true});
  const page=await browser.newPage();
  await page.goto(origin);
  const layers=await page.evaluate(async({source,crop})=>{
    const THREE=await import('three');
    const {SVGLoader}=await import('three/addons/loaders/SVGLoader.js');
    const paths=new SVGLoader().parse(source).paths;
    return paths.flatMap((p,sourceIndex)=>{
      const geometry=new THREE.ShapeGeometry(p.toShapes(),12);
      geometry.computeBoundingBox();
      const box=geometry.boundingBox;
      if(box.isEmpty()||box.min.x<crop[0]||box.min.y<crop[1]||box.max.x>crop[2]||box.max.y>crop[3]){geometry.dispose();return [];}
      const points=geometry.getAttribute('position');
      const xy=[];
      for(let i=0;i<points.count;i++)xy.push(Math.round(points.getX(i)*10000)/10000,Math.round(points.getY(i)*10000)/10000);
      const result={sourceIndex,color:'#'+p.color.getHexString(),xy,indices:[...geometry.index.array]};
      geometry.dispose();return [result];
    });
  },{source,crop});
  if(layers.length!==104)throw new Error(`SVG layout changed: expected 104 logo paths, found ${layers.length}. Inspect the crop before regenerating.`);
  const metadata={source:'LoomOS-panda-ink-clean.svg',sourceSha256,crop,svgToModel:{origin:[513,692],scale:0.0047,center:[0,1.31]}};
  const output='// Generated by npm run build:emblem from original SVG. Do not edit points by hand.\n'
    +'export const EMBLEM_SOURCE = '+JSON.stringify(metadata)+';\n'
    +'export const EMBLEM_LAYERS = [\n'+layers.map(layer=>JSON.stringify(layer)).join(',\n')+'\n];\n';
  await writeFile(new URL('../src/emblem-data.js',import.meta.url),output);
  console.log(`Compiled ${layers.length} original SVG layers (${output.length} bytes); source sha256 ${sourceSha256}`);
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
