test('same-profile explicit reconnect replaces historical stale connection only on success',async t=>{
  const h=harness(t);const first=await h.run({action:'connect',profile_id:P});
  const reloaded=harness(t,h.events);const next='239FEEFA-B53E-4234-822C-8457907654BD';
  reloaded.setHandler(a=>a.includes('connect')?{data:{status:'ok',connection:next}}:null);
  const connected=await reloaded.run({action:'connect',profile_id:P.toLowerCase()});
  assert.equal(connected.runtime,first.runtime);assert.equal(connected.data.connection,next);
  assert.equal(reloaded.calls.filter(a=>a.includes('connect')).length,1);
  await reloaded.run({action:'state'});assert.ok(reloaded.calls.at(-1).includes(next));
  const again=harness(t,reloaded.events);await again.run({action:'state'});assert.ok(again.calls[0].includes(next));
});
