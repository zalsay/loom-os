const P='9080635F-0A64-4ECC-9969-58C9618B5072', C='809A5D77-13E0-4DF3-8792-9EA5F596DF22', F='FBA8FD55-2CE3-49E9-9C68-BEF7C44EACCB';
const receipt={inputReleased:true,artifactsCleaned:true,browserRetained:true,manualInteractionEnabled:true};
function harness(t, events=[]) {
  let tool, handler=()=>null, seq=events.length;
  const calls=[], runtimes=new Set();
  const ctx={effect:f=>f(),tools:{register:d=>{tool=d;return ()=>{};}},sandboxPolicy:{resolve:()=>({mode:'danger-full-access'})},workingDirectory:{ensure:async()=>'/tmp'},subprocess:{resolveExecutable:async p=>p,spawn(spec){
    calls.push(spec.argv);
    const a=spec.argv, ri=a.indexOf('--runtime'); if (ri>=0) runtimes.add(a[ri+1]);
    let result=handler(a);
    if(result instanceof Error) throw result;
    result ??= {data:a.includes('connect')?{status:'ok',connection:C}:a.includes('observe')?{status:'ok',frame:F,screenshotPath:'/tmp/test.png'}:a.includes('release')?{status:'ok',controlReleased:receipt}:{status:'ok'}};
    const {exitCode=0,signal=null,lossy=false}=result;
    return {done:Promise.resolve({exitCode,signal}),collected:{stdout:{readFrom:()=>({text:result.stdout ?? JSON.stringify(result.data),lossy})},stderr:{readFrom:()=>({text:result.stderr ?? '',lossy:false})}}};
  }}};
  apply(ctx);
  // Only remove directories generated by this test's connect calls, never history paths.
  t.after(async()=>{for(const r of runtimes) if(!r.endsWith('history-fixture')) await rm(r,{recursive:true,force:true});});
  const exec={agent:{id:'owner',session:{snapshotEvents:()=>events}},signal:new AbortController().signal};
  async function run(a) {
    const callId=String(++seq);
    events.push({type:'tool/call',data:{name:'sfa',callId,arguments:JSON.stringify(a)}});
    const value=await tool.execute(a,{...exec,callId});
    events.push({type:'tool/result',data:{message:{toolCallId:callId,content:[{type:'text',text:JSON.stringify(value)}]}}});
    return value;
  }
  return {calls,events,run,setHandler:h=>handler=h};
}
test('invalid Space CLI exit does not poison observe input or release',async t=>{
  const h=harness(t);await h.run({action:'connect',profile_id:P});await h.run({action:'observe'});
  h.setHandler(a=>a.includes('Space')?{exitCode:1,stdout:'',stderr:'control: unavailable or invalid request\n'}:null);
  const failure=await h.run({action:'press',frame:F,key:'Space'});
  assert.equal(failure.exitCode,1);assert.equal(failure.stderr,'control: unavailable or invalid request\n');assert.notEqual(failure.uncertain,true);
  assert.equal(h.calls.filter(a=>a.includes('Space')).length,1);
  await h.run({action:'observe'});await h.run({action:'press',frame:F,key:'Down'});
  assert.equal((await h.run({action:'release'})).releaseVerified,true);
});
test('uncertain backend reply and thrown transport error do not block subsequent explicit release',async t=>{
  for(const failure of [{exitCode:1,data:{status:'error',error:'INDETERMINATE_RESULT'}},new Error('transport closed')]) {
    const h=harness(t);await h.run({action:'connect',profile_id:P});h.setHandler(a=>a.includes('navigate')?failure:null);
    if(failure instanceof Error) await assert.rejects(h.run({action:'navigate',url:'https://example.com'}),/transport closed/);
    else assert.equal((await h.run({action:'navigate',url:'https://example.com'})).data.error,'INDETERMINATE_RESULT');
    assert.equal(h.calls.filter(a=>a.includes('navigate')).length,1);
    assert.equal((await h.run({action:'release'})).releaseVerified,true);
  }
});
