test('failed connect allows launch and cleanup without a connection, including after reload',async t=>{
  const h=harness(t);h.setHandler(a=>a.includes('connect')?{exitCode:1,data:{status:'error',error:'SESSION_NOT_FOUND'}}:null);
  const failed=await h.run({action:'connect',profile_id:P});
  h.setHandler(()=>null);
  assert.equal((await h.run({action:'launch',profile_id:P})).exitCode,0);
  const reloaded=harness(t,h.events);
  const cleaned=await reloaded.run({action:'release'});
  assert.equal(cleaned.stop.exitCode,0);
  assert.equal(cleaned.runtime,failed.runtime);
  assert.equal(reloaded.calls.length,1);
  assert.ok(reloaded.calls[0].includes('stop'));
  const next=harness(t,reloaded.events);
  await next.run({action:'launch',profile_id:P});
  assert.equal(next.calls.length,1);
});
